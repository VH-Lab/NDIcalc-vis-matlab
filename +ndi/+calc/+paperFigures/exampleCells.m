function cells = exampleCells(study)
% EXAMPLECELLS - The example cells shown from each session of the paper's dataset
%
% CELLS = NDI.CALC.PAPERFIGURES.EXAMPLECELLS(STUDY)
%
% Returns an N x 2 cell array of the element names and references of the
% example cells for one of the two sessions in the calculators paper's
% example dataset. STUDY is one of:
%
%   "griswold"        - the session from Griswold and Van Hooser (2025); its
%                       cells are used for the orientation/direction,
%                       contrast, contrast sensitivity, spatial frequency and
%                       temporal frequency examples. They are the first 15
%                       cells, in name order, that have orientation/direction
%                       results.
%   "suarezCasanova"  - the session from the Suarez Casanova et al. study; its
%                       cells are used for the speed tuning and Hartley
%                       examples.
%
% See also: ndi.calc.paperFigures.findElements

arguments
    study (1,1) string {mustBeMember(study, ["griswold", "suarezCasanova"])}
end

switch study
    case "griswold"
        cells = { ...
            'LeftHemisphere_1', 1; ...
            'LeftHemisphere_2', 1; ...
            'LeftHemisphere_5', 1; ...
            'LeftHemisphere_7', 1; ...
            'LeftHemisphere_17', 1; ...
            'LeftHemisphere_18', 1; ...
            'LeftHemisphere_20', 1; ...
            'LeftHemisphere_21', 1; ...
            'LeftHemisphere_22', 1; ...
            'LeftHemisphere_23', 1; ...
            'LeftHemisphere_24', 1; ...
            'LeftHemisphere_25', 1; ...
            'LeftHemisphere_26', 1; ...
            'LeftHemisphere_27', 1; ...
            'LeftHemisphere_28', 1};
    case "suarezCasanova"
        cells = { ...
            'leftcortex_11', 1; ...
            'leftcortex_22', 1; ...
            'leftcortex_26', 1; ...
            'leftcortex_31', 1};
end

end
